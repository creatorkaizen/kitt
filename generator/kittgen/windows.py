"""Generate a Windows native keyboard-layout C source file (KBDTABLES) from a
validated `LayoutSpec`.

This module turns the platform-independent Kitt model (model.py) into the
concrete data tables the Windows kbdlayout DLL interface expects, as declared
in the Windows Driver Kit header:

    C:\\Program Files (x86)\\Windows Kits\\10\\Include\\10.0.19041.0\\um\\kbd.h

It follows the standard structure used by Microsoft's own kbdxx.c samples
(e.g. kbdus.c): an `aVkToBits[]` / `aModification[]` modifier table, one or
more `aVkToWchars*[]` tables grouped by shift-state count, an `aVSCtoVK[]`
scan-code table, an optional `aDeadKey[]` table, and a root `KBDTABLES`
struct returned by an exported `KbdLayerDescriptor()` function.

Scope for Kitt (KITT_ARCHITECTURE.md section 8):
  - Kitt only uses two modifier states: base and shift. It does not use
    AltGr/KANA/etc.
  - Ctrl (alone or combined with Alt) must keep behaving like a normal
    Windows shortcut modifier, not emit letters (architecture section 7,
    "Safety invariants": "Ctrl shortcuts should not unexpectedly emit
    letters"). This is implemented by marking the CTRL and CTRL+ALT
    modification-bit combinations as SHFT_INVALID in `aModification[]`,
    exactly like Microsoft's own US layout does for undefined shift states.
  - The scan-code -> virtual-key table is the standard PC/AT-101 layout
    (the same one used by kbdus.c and friends): Kitt changes what each VK
    *produces*, not which physical key maps to which VK. This keeps every
    physical key's position identical to a normal US/ISO layout.

This module does not modify model.py/parser.py/validation.py; it only
imports and consumes their public types.
"""

from __future__ import annotations

from dataclasses import dataclass

from .model import BASE, SHIFT, DeadKeyCombination, DeadKeySpec, KeyOutputs, LayoutSpec

