# The four Turkish-Q-specific keys occupy scan-code positions that already
# exist in the standard table above (they are OEM punctuation positions on a
# US keyboard, relabeled on a Turkish Q keyboard). No extra scan-code rows
# are needed for them: PHYSICAL_KEY_TO_VK already routes them to a VK_OEM_*
# constant that appears in STANDARD_SCANCODE_TO_VK.

# aVkToBits[]: which real modifier keys set which bit. Standard 3-bit
# layout used by Microsoft's own samples: bit 0 = SHIFT, bit 1 = CTRL,
# bit 2 = ALT (KBDSHIFT/KBDCTRL/KBDALT).
VK_TO_BITS: tuple[tuple[str, str], ...] = (
    ("VK_SHIFT", "KBDSHIFT"),
    ("VK_CONTROL", "KBDCTRL"),
    ("VK_MENU", "KBDALT"),
)

# aModification[]: maps the 3-bit (CTRL, ALT, SHIFT) combination to a
# Modification Number, i.e. an index into each aVkToWchars*.wch[] array.
# Kitt only defines base (index 0) and shift (index 1) outputs. Every
# combination involving CTRL and/or ALT is marked SHFT_INVALID so Ctrl+letter
# keeps behaving like an ordinary Windows shortcut instead of emitting a
# Ukrainian letter (KITT_ARCHITECTURE.md section 7, "Safety invariants").
# Index is (CTRL<<2 | ALT<<1 | SHIFT), matching kbd.h's own example table.
MODIFICATION_NUMBERS: tuple[str, ...] = (
    "0",             # 000 <none>            -> base
    "1",             # 001 SHIFT             -> shift
    "SHFT_INVALID",  # 010 ALT
    "SHFT_INVALID",  # 011 SHIFT ALT
    "SHFT_INVALID",  # 100 CTRL
    "SHFT_INVALID",  # 101 SHIFT CTRL
    "SHFT_INVALID",  # 110 CTRL ALT
    "SHFT_INVALID",  # 111 SHIFT CTRL ALT
)

# Kitt keys are always CAPLOK: Caps Lock affects them exactly like Shift,
# matching behavior.caps_lock: letters_only in the YAML (every mapped key
# here is a letter).
KEY_ATTRIBUTES = "CAPLOK"

