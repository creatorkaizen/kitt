@dataclass(frozen=True)
class _WcharRow:
    """One row of the VK_TO_WCHARS2 table: a single VK's base+shift output."""

    vk: str
    base: str
    shift: str
    comment: str


def _wchar_literal(ch: str | None) -> str:
    """Render a single output character as a C WCHAR literal, or WCH_NONE."""
    if ch is None:
        return "WCH_NONE"
    if len(ch) != 1:
        raise ValueError(f"expected a single Unicode scalar output, got {ch!r}")
    return f"0x{ord(ch):04X}"


def _dead_key_wchar_literal() -> str:
    return "WCH_DEAD"


def _collect_wchar_rows(spec: LayoutSpec) -> list[_WcharRow]:
    """Build one VK_TO_WCHARS2 row per normal (non-dead-key) physical key,
    plus one row per dead key's trigger VK (marked WCH_DEAD/WCH_DEAD)."""
    rows: list[_WcharRow] = []

    for physical_key in sorted(spec.keys):
        outputs: KeyOutputs = spec.keys[physical_key]
        vk = _vk_for_physical_key(physical_key)
        base = outputs.get(BASE)
        shift = outputs.get(SHIFT)
        rows.append(
            _WcharRow(
                vk=vk,
                base=_wchar_literal(base),
                shift=_wchar_literal(shift),
                comment=f"{physical_key}: base={base!r} shift={shift!r}",
            )
        )

    for dead_key_name in sorted(spec.dead_keys):
        vk = _vk_for_physical_key(dead_key_name)
        rows.append(
            _WcharRow(
                vk=vk,
                base=_dead_key_wchar_literal(),
                shift=_dead_key_wchar_literal(),
                comment=f"{dead_key_name}: dead key (WCH_DEAD)",
            )
        )

    rows.sort(key=lambda r: r.vk)
    return rows


def _c_vk_expr(vk_name: str) -> str:
    """Render a VK_* name as a C expression usable in a static initializer.

    winuser.h deliberately does NOT #define VK_A..VK_Z or VK_0..VK_9 (see
    its own comment: "VK_A - VK_Z are the same as ASCII 'A' - 'Z'"). Using
    the bare name (e.g. "VK_A") in generated C therefore fails to compile
    with C2065 "undeclared identifier" — confirmed by actually compiling
    the generated kitt_tables.c with MSVC. Every other VK_* constant (the
    function keys, VK_OEM_*, VK_SHIFT, etc.) IS #define'd in winuser.h and
    must be emitted as-is.
    """
    if len(vk_name) == 4 and vk_name.startswith("VK_") and vk_name[3].isalpha():
        return f"'{vk_name[3]}'"
    if len(vk_name) == 4 and vk_name.startswith("VK_") and vk_name[3].isdigit():
        return f"'{vk_name[3]}'"
    return vk_name


def _vk_for_physical_key(physical_key: str) -> str:
    """Resolve a YAML physical_key identifier to a VK_* C expression.

    `Y` (the dead-key trigger name used in kitt.uk-UA.yaml's `dead_keys`
    section) is a bare Latin letter identifier, not a `KeyY`-style name, so
    it is handled the same way KeyY would be.
    """
    if physical_key in PHYSICAL_KEY_TO_VK:
        return _c_vk_expr(PHYSICAL_KEY_TO_VK[physical_key])
    if len(physical_key) == 1 and physical_key.isalpha():
        return _c_vk_expr(f"VK_{physical_key.upper()}")
    raise ValueError(
        f"no known VK_* mapping for physical_key {physical_key!r}; "
        "add it to PHYSICAL_KEY_TO_VK in windows.py"
    )


def _collect_dead_key_entries(spec: LayoutSpec) -> list[tuple[str, str, str, str]]:
    """Build DEADTRANS(...) rows: (following_char_literal, accent_char_literal,
    composed_char_literal, comment).

    Windows identifies "which dead key" a DEADKEY row belongs to by the
    literal WCHAR that dead key's *base* (unshifted) row produced before it
    was marked WCH_DEAD in aVkToWchars — see kbd.h's DEADTRANS macro:
    `dwBoth = MAKELONG(ch, accent)`, where `accent` is that identifying
    character and `ch` is the character physically typed next. Kitt's dead
    key always identifies as `dead_spec.alone.base` (e.g. Y's identity is
    'й', not 'Й'), matching how a real Windows dead key is a single VK_DEAD
    entry, not one per shift state.

    For the following key, Kitt defines one combination output per modifier
    (base/shift) under each combination entry (e.g. Y+A: base='я',
    shift='Я'). The character "physically typed next" for a given shift
    state is the *following* key's own output under that same shift state,
    e.g. Shift+A after the dead key types 'А' (KeyA.shift), and Windows
    composes it against the accent to produce 'Я' (the combination's shift
    output). So each combination entry contributes one DEADTRANS row per
    modifier it defines, using the *following key's own* output as `ch`.
    """
    entries: list[tuple[str, str, str, str]] = []

    for dead_key_name in sorted(spec.dead_keys):
        dead_spec: DeadKeySpec = spec.dead_keys[dead_key_name]
        accent_char = dead_spec.alone.get(BASE)
        if accent_char is None:
            raise ValueError(
                f"dead_keys.{dead_key_name}.alone has no 'base' output; "
                "cannot identify this dead key for DEADTRANS"
            )

        for combo_key in sorted(dead_spec.combinations):
            combo: DeadKeyCombination = dead_spec.combinations[combo_key]
            following_key_outputs = spec.keys.get(combo_key)
            for modifier, composed_char in sorted(combo.by_modifier.items()):
                following_char = (
                    following_key_outputs.get(modifier)
                    if following_key_outputs is not None
                    else None
                )
                if following_char is None:
                    # The following physical key has no output of its own
                    # under this modifier (e.g. it is itself another
                    # dead-key trigger, or simply undefined) — nothing to
                    # compose against, so skip rather than guess.
                    continue
                entries.append(
                    (
                        _wchar_literal(following_char),
                        _wchar_literal(accent_char),
                        _wchar_literal(composed_char),
                        f"{dead_key_name} + {combo_key}.{modifier} "
                        f"({following_char!r}) -> {composed_char!r}",
                    )
                )

    return entries


def generate_kbdtables_source(spec: LayoutSpec) -> str:
    """Generate a complete .c source file implementing KBDTABLES for `spec`.

    The returned string is a self-contained translation unit: it includes
    <windows.h> and "kbd.h", defines every table KBDTABLES references, and
    exports `KbdLayerDescriptor()` returning a pointer to the populated
    struct, matching the standard pattern used by Microsoft's WDK keyboard
    layout samples (kbdxx.c).
    """
    lines: list[str] = []
    lines.append(GENERATED_FILE_WARNING)
    lines.append(f"// Layout: {spec.metadata.name} ({spec.metadata.id}), "
                 f"version {spec.metadata.version}")
    lines.append(f"// Language: {spec.metadata.language}")
    lines.append(f"// Description: {spec.metadata.description}")
    lines.append("")
    lines.append("#include <windows.h>")
    lines.append('#include "kbd.h"')
    lines.append("")

    lines.extend(_render_vk_to_bits())
    lines.append("")
    lines.extend(_render_modifiers())
    lines.append("")
    lines.extend(_render_vk_to_wchars(spec))
    lines.append("")
    lines.extend(_render_vk_to_wchar_table())
    lines.append("")

    wchar_rows_present = bool(spec.keys) or bool(spec.dead_keys)
    dead_key_entries = _collect_dead_key_entries(spec)
    if dead_key_entries:
        lines.extend(_render_dead_keys(dead_key_entries))
        lines.append("")

    lines.extend(_render_scancode_to_vk())
    lines.append("")
    lines.extend(_render_key_names())
    lines.append("")
    lines.extend(_render_kbdtables(has_dead_keys=bool(dead_key_entries)))
    lines.append("")
    lines.extend(_render_descriptor_function())
    lines.append("")

    _ = wchar_rows_present  # keys/dead_keys always populate at least one table
    return "\n".join(lines) + "\n"


def _render_vk_to_bits() -> list[str]:
    lines = [
        "// aVkToBits[]: real modifier keys -> modifier bitmask.",
        "// Kitt only uses SHIFT for its own letter outputs; CTRL/ALT bits are",
        "// still tracked so aModification[] can mark those combinations",
        "// SHFT_INVALID (see MODIFICATION_NUMBERS comment in windows.py).",
        f"static VK_TO_BIT {C_TABLE_NAME_VK_TO_BITS}[] = {{",
    ]
    for vk, bit in VK_TO_BITS:
        lines.append(f"    {{ {vk}, {bit} }},")
    lines.append("    { 0, 0 },")
    lines.append("};")
    return lines


def _render_modifiers() -> list[str]:
    lines = [
        "// aModification[]: (CTRL,ALT,SHIFT) bit combination -> Modification",
        "// Number (index into each VK_TO_WCHARS2.wch[]). Only base (0) and",
        "// shift (1) are defined; every state involving CTRL and/or ALT is",
        "// SHFT_INVALID so Ctrl+<letter> keeps working as a normal Windows",
        "// shortcut instead of emitting a Ukrainian letter.",
        f"static MODIFIERS {C_TABLE_NAME_MODIFIERS} = {{",
        f"    {C_TABLE_NAME_VK_TO_BITS},",
        "    7,  // wMaxModBits (CTRL|ALT|SHIFT = 0x7)",
        "    {",
    ]
    for value in MODIFICATION_NUMBERS:
        lines.append(f"        {value},")
    lines.append("    },")
    lines.append("};")
    return lines


def _render_vk_to_wchars(spec: LayoutSpec) -> list[str]:
    rows = _collect_wchar_rows(spec)
    lines = [
        "// aVkToWchars2[]: one row per Kitt-mapped VK, with 2 shift states",
        "// (index 0 = base, index 1 = shift), matching aModification[] above.",
        f"static VK_TO_WCHARS2 {C_TABLE_NAME_VK_TO_WCHARS}[] = {{",
    ]
    for row in rows:
        lines.append(
            f"    {{ {row.vk}, {KEY_ATTRIBUTES}, {{ {row.base}, {row.shift} }} }},"
            f"  // {row.comment}"
        )
    lines.append("    { 0, 0, { 0, 0 } },  // terminator")
    lines.append("};")
    return lines


def _render_vk_to_wchar_table() -> list[str]:
    lines = [
        "// aVkToWcharTable[]: groups of VK_TO_WCHARS tables by shift-state",
        "// count. Kitt only has one group (2 shift states: base, shift).",
        f"static VK_TO_WCHAR_TABLE {C_TABLE_NAME_VK_TO_WCHAR_TABLE}[] = {{",
        f"    {{ (PVK_TO_WCHARS1)(void*){C_TABLE_NAME_VK_TO_WCHARS}, "
        "2, sizeof(VK_TO_WCHARS2) },",
        "    { NULL, 0, 0 },  // terminator",
        "};",
    ]
    return lines


def _render_dead_keys(entries: list[tuple[str, str, str, str]]) -> list[str]:
    lines = [
        "// aDeadKey[]: dead-key combination -> composed character.",
        "// dwBoth = MAKELONG(following_char, accent_char): low word is the",
        "// character typed after the dead key, high word is the dead key's",
        "// own accent (\"alone\") character.",
        f"static DEADKEY {C_TABLE_NAME_DEAD_KEY}[] = {{",
    ]
    for following_lit, accent_lit, composed_lit, comment in entries:
        lines.append(
            f"    DEADTRANS({following_lit}, {accent_lit}, {composed_lit}, DKF_DEAD),"
            f"  // {comment}"
        )
    lines.append("    DEADTRANS(0, 0, 0, 0),  // terminator")
    lines.append("};")
    return lines


def _render_scancode_to_vk() -> list[str]:
    max_scancode = max(code for code, _ in STANDARD_SCANCODE_TO_VK)
    lines = [
        "// aVscToVk[]: standard PC/AT-101 scan-code -> virtual-key table.",
        "// Kitt does not remap physical key positions, only what each VK",
        "// produces, so this table matches an ordinary US/ISO layout.",
        f"static USHORT {C_TABLE_NAME_VSC_TO_VK}[] = {{",
    ]
    # pusVSCtoVK is indexed directly by scan code (Windows reads
    # pusVSCtoVK[vsc]), so index 0 must correspond to scan code 0x00, not
    # scan code 0x01 — confirmed by loading this generator's own compiled
    # DLL and reading back pusVSCtoVK, which caught an earlier off-by-one
    # here (index 0 held scan code 1's VK, shifting every entry by one).
    table = {code: vk for code, vk in STANDARD_SCANCODE_TO_VK}
    for scancode in range(0, max_scancode + 1):
        vk = table.get(scancode)
        vk_expr = _c_vk_expr(vk) if vk is not None else "0"
        lines.append(f"    /* 0x{scancode:02X} */ {vk_expr},")
    lines.append("};")
    return lines


def _render_key_names() -> list[str]:
    # Minimal key-name table: Windows falls back to defaults for anything not
    # listed, and Kitt does not rename any key, so this is intentionally
    # empty (terminator-only), matching kbd.h's documented "table" shape.
    lines = [
        "// aKeyNames[]: display names for keys shown in OS key-name UI.",
        "// Kitt does not rename any key, so this table only has the",
        "// required NULL terminator.",
        f"static VSC_LPWSTR {C_TABLE_NAME_KEY_NAMES}[] = {{",
        "    { 0, NULL },",
        "};",
    ]
    return lines


def _render_kbdtables(*, has_dead_keys: bool) -> list[str]:
    dead_key_field = f"{C_TABLE_NAME_DEAD_KEY}" if has_dead_keys else "NULL"
    lines = [
        "// Root KBDTABLES struct: ties every table above together. Returned",
        f"// by {C_FUNCTION_NAME}() below, per the standard WDK keyboard-",
        "// layout DLL export contract.",
        "static KBDTABLES kitt_KbdTables = {",
        f"    &{C_TABLE_NAME_MODIFIERS},              // pCharModifiers",
        f"    {C_TABLE_NAME_VK_TO_WCHAR_TABLE},        // pVkToWcharTable",
        f"    {dead_key_field},                        // pDeadKey",
        f"    {C_TABLE_NAME_KEY_NAMES},                // pKeyNames",
        "    NULL,                                    // pKeyNamesExt",
        "    NULL,                                    // pKeyNamesDead",
        f"    {C_TABLE_NAME_VSC_TO_VK},                // pusVSCtoVK",
        f"    (BYTE)(sizeof({C_TABLE_NAME_VSC_TO_VK}) / "
        f"sizeof({C_TABLE_NAME_VSC_TO_VK}[0])),  // bMaxVSCtoVK",
        "    NULL,                                    // pVSCtoVK_E0",
        "    NULL,                                    // pVSCtoVK_E1",
        "    0,                                       // fLocaleFlags (no AltGr)",
        "    0,                                       // nLgMax (no ligatures)",
        "    0,                                       // cbLgEntry",
        "    NULL,                                    // pLigature",
        "    0,                                       // dwType",
        "    0,                                       // dwSubType",
        "};",
    ]
    return lines


def _render_descriptor_function() -> list[str]:
    lines = [
        "// Standard WDK keyboard-layout DLL export: returns the KBDTABLES",
        "// struct describing this layout. See kbd.def/.def export file for",
        "// the corresponding EXPORTS entry.",
        f"__declspec(dllexport) PKBDTABLES WINAPI {C_FUNCTION_NAME}(VOID)",
        "{",
        "    return &kitt_KbdTables;",
        "}",
    ]
    return lines
