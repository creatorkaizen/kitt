"""Generate a Windows native keyboard-layout C source file (KBDTABLES) from a
validated `LayoutSpec`.

This module turns the platform-independent Kitt model (model.py) into the
concrete data tables the Windows kbdlayout DLL interface expects, as declared
in the Windows Driver Kit header:

    C:\\Program Files (x86)\\Windows Kits\\10\\Include\\10.0.19041.0\\um\\kbd.h

Generation strategy: override, don't rebuild
--------------------------------------------

Kitt is a Ukrainian mnemonic layout for a **Turkish Q physical keyboard**.
It changes what ~29 keys produce under base and Shift. It has no opinion
whatsoever about the other several hundred (VK, shift-state) pairs a real
keyboard layout has to define — AltGr output, Ctrl+Alt output, the numeric
keypad, the `"`/`é` key, the accent dead keys, the extended navigation
scan codes, and so on.

Earlier revisions of this generator built the tables bottom-up: emit a row
for each Ukrainian letter, then bolt on a hand-maintained list of "extra"
keys. That is structurally wrong, because a layout DLL's tables are the
**only** source Windows consults. A VK absent from every `aVkToWchars*`
table produces nothing; a shift state no `aModification[]` entry maps to a
Modification Number is dead. So every key nobody thought to list silently
broke, and each round of real-machine testing surfaced another one (first
digits and Space, then arrows and Insert/Delete/Home/End, then AltGr,
Ctrl+Alt, `"` and `é`).

This module therefore starts from the **complete** table set of the real
Windows-shipped Turkish Q driver (`turkish_q_reference.py`, dumped from
`KBDTUQ.DLL`) and applies Kitt's mapping as a set of targeted overrides:

  1. Copy every reference table verbatim — modifiers, `aVkToBits[]`, all six
     `VK_TO_WCHARS<n>` groups with their exact `Attributes` (CAPLOK /
     CAPLOKALTGR) flags, all three scan-code tables, the 59-entry dead-key
     table, and `fLocaleFlags` (which includes `KLLF_ALTGR` — omitting it,
     as an earlier revision did, disables AltGr wholesale).
  2. For each physical key in `layout/kitt.uk-UA.yaml`, replace **only**
     modification numbers 0 (base) and 1 (Shift) of that VK's existing row.
     Every other shift state on that row — AltGr, Shift+AltGr, Ctrl+Alt —
     keeps the real Turkish Q value, including any `WCH_DEAD` marker and
     its trailing DEADCHARS row.
  3. Turn Kitt's own dead key (Y) into `WCH_DEAD` for base and Shift, give
     it a DEADCHARS row carrying its identity characters, and append its
     combinations to the reference `DEADTRANS` table.

Safety invariants (KITT_ARCHITECTURE.md section 7) are satisfied by the
reference `aModification[]` table as-is: it already marks the pure-CTRL and
SHIFT+CTRL combinations `SHFT_INVALID`, so Ctrl+<letter> stays a shortcut.
This module copies that table unchanged rather than reinventing it.

This module does not modify model.py/parser.py/validation.py; it only
imports and consumes their public types.
"""

